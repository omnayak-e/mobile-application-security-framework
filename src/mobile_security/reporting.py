import json
from pathlib import Path

def save_report(data, prefix, title="Mobile Application Security Review"):
    prefix = Path(prefix); prefix.parent.mkdir(parents=True, exist_ok=True)
    jp, mp = prefix.with_suffix(".json"), prefix.with_suffix(".md")
    jp.write_text(json.dumps(data, indent=2), encoding="utf-8")
    lines = [f"# {title}", "", "> Static review aid only. Validate each item against the app, build variant, and backend context.", ""]
    if "package" in data:
        lines += [f"- **Package:** `{data['package']}`", f"- **Application element found:** {data['application_present']}", ""]
    findings = data.get("findings", [])
    lines += [f"## Findings ({len(findings)})", ""]
    for i, f in enumerate(findings, 1):
        lines += [f"### {i}. {f['title']}", "", f"- **Severity:** {f.get('severity','info')}",
                  f"- **Category:** {f.get('category','Uncategorised')}", "",
                  f"**Evidence:** {f.get('evidence','Not supplied')}", "",
                  f"**Recommended action:** {f.get('remediation','Review manually.')}", ""]
    if not findings:
        lines.append("No findings were generated by the selected checks. This does not establish that the app is secure.")
    if data.get("notes"):
        lines += ["## Notes", ""] + [f"- {n}" for n in data["notes"]]
    mp.write_text("\n".join(lines)+"\n", encoding="utf-8")
    return jp, mp
